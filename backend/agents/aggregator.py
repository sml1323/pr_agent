def pick_representative(
    group: list[dict[str, Any]], order: tuple[AgentType, ...]
) -> dict[str, Any]:
    """같은 키의 finding 들 중 하나를 대표로 고른다. **필드를 섞지 않는다.**

    ⚠️ 정렬 키가 셋인 건 전부 **결정성**을 위해서다. 하나라도 빠지면 동률에서
       입력 순서에 기대게 되고, 그럼 완료 판정이 같은 입력에 다른 답을 준다.
    """
    rank = {a: i for i, a in enumerate(order)}
    return min(
        group,
        key=lambda f: (
            SEVERITY_RANK[f["severity"]],  # 작을수록 심각 (critical=0)
            -f["confidence"],  # 큰 게 앞
            rank.get(f.get("agent_type", ""), len(order)),  # 출처 순서
            # ⚠️ **내용 타이브레이커** (2026-08-28 에 추가. 없을 때 실제로 깨졌다)
            #
            #    앞의 셋만으로는 **한 관점이 같은 결함을 두 번 뱉을 때** 동률이 남는다.
            #    그건 상상이 아니라 M0 에서 관측된 것이다 (`PLAN.md` G-M0-3:
            #    *"같은 (file, line, category) 에 severity 만 다른 중복이 에이전트 하나의
            #    한 번 호출에서 생성됨"*).
            #
            #    실측 — 이 줄이 없을 때:
            #        원래 순서 → "A 쪽 설명"    뒤집으면 → "B 쪽 설명"
            #
            #    그리고 입력 순서는 **우리가 못 정한다** — 리듀서가 노드 완료 순서대로 쌓고,
            #    그 순서는 비결정적이다 (Lesson 07 에서 실측한 그것).
            #    → 같은 리뷰를 두 번 돌리면 `merged` 의 rationale 이 달라질 수 있었다.
            #      완료 판정 ⓪(결정성)이 셔플만 검사해서 **이걸 못 잡았다** —
            #      측정한 데이터에 완전 동률이 없었기 때문이다. 판정이 통과한 범위가
            #      판정문의 주장보다 좁았던 것이고, 그게 M5 독립 검증이 찾은 것과 같은 종류다.
            #
            #    ⚠️ `line` 과 `rationale` 로 가르는 건 **의미가 있어서가 아니라 안정적이라서**다.
            #       동률이라는 건 "우리 기준으로는 구별이 안 된다"는 뜻이고, 그때 필요한 건
            #       좋은 선택이 아니라 **같은 선택**이다.
            f["line"],
            f["rationale"],
        ),
    )


