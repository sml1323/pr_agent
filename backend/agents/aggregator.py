def aggregate(
    findings: list[dict[str, Any]],
    *,
    order: tuple[AgentType, ...] = ("security", "quality", "testing", "docs"),
) -> list[dict[str, Any]]:
    """관점 넷이 쌓은 findings → 중복이 합쳐진 목록. **순수 함수다** (LangGraph 를 모른다).

    Args:
        findings: `state["findings"]` 그대로. `SourcedFinding.model_dump()` 의 리스트다
            (`state.py` 결정 4 — 체크포인터가 직렬화하므로 pydantic 객체가 아니라 dict).
        order: 대표 선정의 마지막 타이브레이커. 오케스트레이터의 팬아웃 순서를 받는다.
            ⚠️ 인자로 연 이유는 **결정성을 호출자가 볼 수 있게** 하려는 것이다.
               여기 상수로 숨기면 `langgraph_engine.AGENT_TYPES` 와 조용히 어긋난다.

    Returns:
        `MergedFinding.model_dump()` 의 리스트. **정렬돼 있다** — 심각도 → 파일 → category.
        ⚠️ 정렬이 계약의 일부다. 안 하면 dict 순회 순서가 표에 새어 완료 판정이 흔들린다.

    ⚠️ **입력을 안 바꾼다.** `state["findings"]` 는 리듀서가 쌓은 원본이고,
       그건 "누가 무엇을 말했나"의 유일한 기록이다 (INV-4 의 정신).
       실측으로 확인한 것: 리듀서가 붙은 채널은 **덮어쓰기가 원리적으로 불가능**하다 —
       `_aggregate` 가 `{"findings": [...]}` 를 돌려주면 **또 더해진다.**
       그래서 결과는 `merged` 라는 **다른 채널**로 나간다 (`state.py` 참조).
       제약이 하나 이득을 낳았다: 원본이 남으니 **애그리게이터가 뭘 버렸는지 추적된다.**
    """
    groups: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for f in findings:
        groups.setdefault(dedup_key(f), []).append(f)

    merged: list[MergedFinding] = []
    for group in groups.values():
        rep = pick_representative(group, order)

        # 출처는 **관측된 순서가 아니라 팬아웃 순서**로 적는다 — 같은 집합이면 같은 리스트여야
        # 표가 재현된다. `dict.fromkeys` 가 아니라 정렬인 이유: 노드 스케줄링은 비결정적이다
        # (Lesson 07 에서 실측한 그것).
        seen = {f["agent_type"] for f in group if "agent_type" in f}
        sources: list[AgentType] = [a for a in order if a in seen]

        # ⚠️ **출처가 하나도 없으면 여기서 멈춘다** (2026-08-28, 자가 검증에서 실제로 터졌다).
        #
        #    `MergedFinding.sources` 가 `min_length=1` 이라 어차피 pydantic 이 거부하는데,
        #    그때 나오는 건 **날 것의 `ValidationError`** 다 — "왜"를 안 말한다.
        #    실측: 옛 `evals/runs/*.json` 세 파일에 `agent_type` 이 아예 없다
        #    (M0 시절 recon 스크립트가 만든 것). 그걸 `aggregate()` 에 먹이면 터지는데,
        #    메시지만 보면 **우리 버그인지 데이터 문제인지 알 수 없다.**
        #
        #    조용히 넘기지 않는 이유: 출처 없는 merged finding 은 M8 게이트의
        #    커버리지 판정(G2)에 **아무 답도 못 준다.** 그건 이 프로젝트 최악의 시나리오다.
        #    시끄럽게 터지되 **무엇을 고쳐야 하는지 말한다** — 이 레포가 세 번 한 선택이다
        #    (`security.py` 부팅 거부 · `base.py` 거부 시 예외 · `review_diff` 필수 인자).
        if not sources:
            raise ValueError(
                f"출처 없는 finding 을 합칠 수 없다: {group[0]['file']}:{group[0]['category']} "
                f"({len(group)}개). 이 dict 들에 `agent_type` 이 없다 — "
                f"M0 시절 `evals/runs/` 데이터이거나, 출처를 붙이는 자리"
                f"(`base.py:review_diff`)를 우회한 경로다."
            )

        # ⚠️ 생성자를 거치는 게 검증이다 — `line >= 1`, `0 <= confidence <= 1`,
        #    `sources` 최소 1개. INV-3 이 여기서 한 번 더 확인된다.
        #    `**rep` 가 아니라 필드를 골라 넣는 이유: `rep` 에는 `agent_type`(단수)이
        #    들어 있고, 그건 `MergedFinding` 에 없는 필드다. pydantic 기본이
        #    `extra="ignore"` 라 **조용히 무시되지만**, 조용한 건 나중에 물린다.
        merged.append(
            MergedFinding(
                severity=rep["severity"],
                category=rep["category"],
                file=rep["file"],
                line=rep["line"],
                confidence=rep["confidence"],
                rationale=rep["rationale"],
                sources=sources,
                merged_from=len(group),
            )
        )

    merged.sort(key=lambda m: (SEVERITY_RANK[m.severity], m.file, m.category))
    return [m.model_dump() for m in merged]
