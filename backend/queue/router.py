"""잡 큐 — 그림의 ②. M1에서는 **의도된 스텁**이다.

M4에서 Redis + ARQ 로 통째로 갈린다. 지금 이게 있는 이유는 하나다:
인그레스가 10초 안에 답하려면 "받았다"와 "처리한다"를 분리해야 하고,
그 분리선이 여기다. 브로커가 없어도 선은 그을 수 있다.

이 스텁의 알려진 한계 (버그가 아니라 알고 하는 타협):
    · 프로세스가 죽으면 큐도 dedup 기록도 사라진다
    · 워커가 없다. 넣기만 하고 아무도 꺼내지 않는다
    · 여러 프로세스(uvicorn --workers 2)면 각자 다른 기억을 갖는다
M4에서 전부 해결된다. 그때까지 CURRENT.md 에 "이건 스텁"이라고 적어둔다 —
알고 미룬 것과 까먹은 것은 다르다 [02:44:28].

읽고 올 것: learning/lessons/0004-same-delivery-twice.html
"""

from typing import Any

# 처리 대기 중인 잡. M4에서 Redis 리스트가 된다.
_queue: list[dict[str, Any]] = []

# 이미 본 delivery ID. M4에서 Redis SET + TTL 이 된다.
#
# list 가 아니라 set 인 이유: 조회가 O(1) 이다. list 면 배달이 쌓일수록
# "이미 봤나?" 검사가 느려지고, 그 지연이 10초 예산을 갉아먹는다.
_seen_deliveries: set[str] = set()


# ─────────────────────────────────────────────────────────────────────
# TODO(human) ① 중복 판정
#
# "이 배달을 전에 본 적 있나?"에 답하면서 **동시에 기록**해야 한다.
# 확인과 기록이 두 동작으로 갈리면 그 사이에 같은 배달이 끼어든다
# (Lesson 04 함정 ①). 둘을 하나의 동작으로 만들 것.
#
# 힌트: 파이썬 set 에는 "넣으면서 새것이었는지 알려주는" 연산이 직접 있진 않다.
#       하지만 넣기 전후의 무언가를 비교하면 알 수 있다. len() 을 떠올려 볼 것.
#       (set.add() 자체의 반환값은 무엇인지도 확인해 볼 것 — 답이 거기 있진 않다)
#
# 판단 하나 더:
#   delivery_id 가 None 이면? GitHub 은 항상 보내지만, 우리 엔드포인트로는
#   아무나 아무거나 쏠 수 있다(서명은 통과했다 치더라도 헤더는 뺄 수 있다).
#   · 중복이 아닌 걸로 치고 통과시킨다  → 멱등성 방어가 그 요청엔 없는 셈
#   · 중복인 걸로 치고 버린다          → 정상 요청을 잃을 수 있다
#   어느 쪽이 이 시스템에서 덜 나쁜가. INV-2가 막으려는 게 정확히 무엇인지 보고 고를 것.
#
# 틀리면:
#   확인과 기록이 벌어져 있으면, 재배달 두 개가 동시에 왔을 때 둘 다 통과한다.
#   그리고 이 버그는 **한가할 때는 절대 재현되지 않는다.**
# ─────────────────────────────────────────────────────────────────────
def is_duplicate(delivery_id: str | None) -> bool:
    """전에 본 배달이면 True. 처음 보는 배달이면 기록하고 False.

    이름이 질문형인데 부작용(기록)이 있다는 점에 주의. 보통은 나쁜 설계지만
    여기서는 **그 둘을 나눌 수 없는 것**이 요점이라 일부러 붙여 뒀다.
    """

    # 열쇠가 없으면 '같은 배달인지'를 판단할 방법 자체가 없다.
    # 모르는 것을 중복으로 단정하면 정상 요청을 잃는다 — 통과시킨다.
    # 기록도 하지 않는다. None 을 넣으면 헤더 없는 서로 무관한 요청들이
    # 두 번째부터 전부 '이미 본 것'으로 묶여 버린다.
    if delivery_id is None:
        return False

    # 확인과 기록을 하나로. set.add() 는 이미 있는 값이면 크기를 바꾸지 않는다.
    # 따로 `in` 검사를 두면 그 사이에 같은 배달이 끼어든다(Lesson 04 함정 ①).
    before = len(_seen_deliveries)
    _seen_deliveries.add(delivery_id)
    return len(_seen_deliveries) == before


def enqueue(payload: dict[str, Any]) -> None:
    """리뷰할 잡을 큐에 넣는다.

    M4에서 이 함수 본문만 Redis 로 갈린다. 호출부(app.py)는 안 바뀐다 —
    그게 이 함수가 존재하는 이유다.
    """
    _queue.append(payload)


def queue_depth() -> int:
    """큐에 쌓인 잡 수. 데모와 테스트가 '진짜 들어갔는지' 확인하는 창구다."""
    return len(_queue)


def reset() -> None:
    """테스트·데모용 초기화. 프로덕션 경로에서는 부르지 않는다."""
    _queue.clear()
    _seen_deliveries.clear()
