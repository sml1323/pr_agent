"""워크플로 엔진의 추상 계약.

이 파일에는 **LangGraph 라는 단어가 한 번도 안 나온다.** 그게 이 파일의 존재 이유다.

왜 추상부터 만드나
------------------
LangGraph 선택은 **되돌릴 수 있는 결정**이다 [01:38:27]. MVP 에 맞아서 골랐을 뿐,
Temporal 로 갈아탈 이유(내구성 보장, 엔터프라이즈 성숙도)가 생길 수 있다.
그때 **클래스 하나를 추가하는 것으로 끝나야** 한다 — 호출하는 쪽 코드는 안 고치고.

그래서 노출하는 것은 세 메서드뿐이다 [01:40:33]:

    run()        새 리뷰를 시작한다
    resume()     죽었다 살아난 뒤 이어서 돌린다
    get_state()  지금 어디까지 갔나

⚠️ 이 셋보다 많이 노출하면 추상이 새기 시작한다. LangGraph 의 `Send`, `Command`,
   `interrupt` 같은 개념이 시그니처에 나타나는 순간, 갈아탈 때 호출부까지 고쳐야 한다.

전체 그림에서 어디인가
----------------------
    PR → ① 웹훅 → ② 큐 → ③ 워커 → **④ 여기서 그래프가 돈다** → ⑤ 애그리게이터 → ⑥ 게이트

③ 워커가 큐에서 잡을 꺼내 `run()` 을 부른다. 워커가 죽으면 다음 워커가 `resume()` 을 부른다.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any


class WorkflowEngine(ABC):
    """리뷰 워크플로를 돌리는 엔진. 구현체는 `langgraph_engine.py`.

    ⚠️ 그래프의 **조립**(노드 등록 → 엣지 연결 → compile)은 이 계약에 안 나온다.
       구현체의 `__init__` 에서 한 번 하고 끝이다. 아래 세 메서드는 전부
       **이미 조립된 그래프를 쓰는 쪽**이다. 조립이 시그니처에 나타나는 순간
       "LangGraph 를 조립한다"가 계약이 되어버려서 갈아탈 수 없다.
    """

    # ── 확정된 결정 (2026-08-19) — 왜 이렇게 골랐나 ──────────────
    #
    # 결정 1 · 세 메서드가 같은 식별자 `review_key: str` 하나를 받는다
    #
    #   · **저장이 아니라 계산으로 얻는 값이다.** 재료는 repo · pr_number · head_sha.
    #     `kill -9` 되면 run() 의 반환값은 존재한 적이 없으므로, 재개하는 워커는
    #     같은 재료로 **다시 계산해서** 같은 열쇠를 얻어야 한다.
    #     → 004 의 `reviews_unique_head` 와 같은 재료다. 거긴 중복 방지, 여긴 재개용 열쇠.
    #
    #   · **`head_sha` 가 재료에 꼭 들어간다.** 빠지면 같은 PR 의 새 커밋이
    #     이전 리뷰의 체크포인트를 물려받아 "이미 다 끝났다"로 판정된다 —
    #     새 코드를 아무도 안 보는 채로 조용히 통과한다.
    #
    #   · **계산은 호출자가 한다.** 엔진은 PR 이 뭔지 몰라도 된다. 그래서 이
    #     인터페이스가 GitHub 도 DB 도 모르는 상태로 남는다.
    #
    #   · **`str` 인 이유**: 004 의 `reviews.id`(BIGSERIAL, 정수)와 **일부러 다르게** 둔다.
    #     정수로 두면 둘이 같은 것처럼 읽히는데, 엔진은 DB 를 모른다. 매핑이 필요하면
    #     그건 워커의 일이지 엔진의 일이 아니다.
    #
    # 결정 2 · `run()` 과 `resume()` 은 아무것도 안 돌려준다 (`None`)
    #
    #   · **진실의 원천은 체크포인터 하나다.** run() 이 최종 state 를 또 돌려주면
    #     같은 사실이 두 곳에 있게 되고, 둘이 어긋날 때 누가 맞는지 규칙이 필요해진다.
    #
    #   · **`kill -9` 되면 반환값은 애초에 없다.** 그래서 호출부는 *어차피*
    #     `get_state()` 경로를 갖춰야 한다. 경로가 하나뿐이면 코드가 갈리지 않는다
    #     ("정상 종료면 반환값을 보고, 죽었으면 조회한다" 같은 분기가 안 생긴다).
    #
    #   · ⚠️ **일부러 좁게 잡은 것이다.** 넓히는 건 호출부를 안 깨지만
    #     좁히는 건 깬다. M8 에서 "GitHub 게시를 그래프 안의 노드가 하나 /
    #     워커가 하나"가 정해지면 다시 본다 — 워커가 한다면 여기서
    #     findings 와 decision 을 받아야 하므로 반환 타입이 바뀐다.
    #
    # 결정 3 · `get_state()` 는 `dict[str, Any]`
    #
    #   · 우리 타입으로 좁히고 싶지만 **그 타입이 아직 없다.** state 정의가
    #     M5-2 의 일이고, 최종 모양은 M6(애그리게이터)에서야 확정된다.
    #     없는 타입을 지금 지어내면 상상으로 만든 감으로 계약을 고정하는 것이다.
    #
    #   · ⚠️ 대신 구현체가 지킬 것: LangGraph 의 `StateSnapshot` 을 **그대로
    #     돌려주면 안 된다.** 평범한 dict 로 풀어서 준다. 그러지 않으면
    #     "이 파일에 LangGraph 가 안 나온다"는 이 모듈의 주장이 거짓이 된다.
    # ─────────────────────────────────────────────────────────────

    @abstractmethod
    def run(self, review_key: str, diff: str) -> None:
        """새 리뷰를 시작한다. 조립된 그래프를 처음부터 끝까지 돌린다.

        Args:
            review_key: repo · pr_number · head_sha 로 계산된 열쇠. 호출자가 만든다.
            diff: 검토할 diff 원문. ⚠️ 신뢰 경계 밖의 문자열이다 (Lesson 02).
        """
        ...

    @abstractmethod
    def resume(self, review_key: str) -> None:
        """중단된 리뷰를 체크포인트에서 이어 돌린다.

        ⚠️ INV-2 가 여기 걸린다 — 이미 끝난 노드를 다시 호출하면
        같은 리뷰에 LLM 호출이 두 번 나간다. 체크포인터가 그걸 막아야 한다.

        `run()` 과 같은 `review_key` 를 받는 것이 이 메서드가 성립하는 조건이다.
        열쇠를 계산으로 얻기 때문에, 죽은 워커가 뭘 반환했는지 몰라도 재개할 수 있다.
        """
        ...

    @abstractmethod
    def get_state(self, review_key: str) -> dict[str, Any]:
        """지금 어디까지 갔나. 대시보드와 워커 복구가 읽는다.

        아직 안 끝난 리뷰에도 부를 수 있어야 한다 — 그게 이 메서드의 존재 이유다.
        """
        ...
