-- ─────────────────────────────────────────────────────────────────────
-- cost_usd / latency_ms / tokens 를 이렇게 정한 근거
--
-- 1. cost_usd 는 NUMERIC(10, 6) — 부동소수점이 아니다
--    DOUBLE PRECISION 은 2진 분수라 0.1 을 정확히 표현하지 못한다. $0.004 를 만 번
--    더하면 $40 이 아니라 $39.99999... 나 $40.00001 이 나온다. 한 번은 무해하지만
--    SUM() 이 이 표의 주 용도이고, M10(비용 관측)이 범위 밖이라 대조할 다른 출처가 없다.
--    (10, 6) = 전체 10자리 중 소수 6자리 → 최대 $9999.999999. 이벤트 하나가 그보다
--    비쌀 수 없고, 소수 6자리면 $0.000001 단위까지 적힌다.
--    정밀도를 안 적은 그냥 NUMERIC 은 "아무 크기나 허용"이라 제약이 없다 —
--    스키마가 잡아줄 수 있는 실수(단위를 센트로 착각해 100배 큰 값)를 안 잡는다.
--
-- 2. latency_ms 와 tokens 는 INTEGER — NUMERIC 이 아니다
--    밀리초 2100.5, 토큰 1840.3 같은 값은 존재하지 않는다. 소수점이 필요 없으면
--    쓰지 않는다. NUMERIC 은 정확하지만 가변 길이라 저장 공간이 크고 연산이 느리다.
--    INTEGER 상한 21억 = 약 24일. LLM 호출 하나가 24일 걸리는 일은 없으므로 충분하다.
--    ⚠️ 만약 latency 를 마이크로초로 바꾼다면 21억µs = 35분이라 좁아진다.
--       단위를 컬럼 이름에 박아둔 이유 — 이름이 _ms 면 마이크로초로 넣는 사고가 준다.
--
-- 3. 셋 다 NULL 허용 — NOT NULL 로 박지 않는다
--    웹훅 수신(agent='webhook')은 LLM 을 부르지 않는다. cost_usd 와 tokens 가 없다.
--    "없음"을 0 으로 적으면 거짓말이 된다 — 0 은 "불렀고 공짜였다"는 뜻이고,
--    AVG(cost_usd) 가 공짜 이벤트에 끌려 내려간다. NULL 은 집계에서 빠진다.
--    그래서 "LLM 호출의 평균 비용"이 NULL 쪽에서만 옳은 답이 나온다.
--
--    latency_ms 는 모든 이벤트에 값이 있을 것 같지만 역시 NULL 허용으로 둔다.
--    **되돌리기 비용이 비대칭이기 때문**이다:
--      느슨하게 시작 → 나중에 NOT NULL 로 조이려면 기존 행을 채워야 한다 (어렵지만 가능)
--      NOT NULL 로 시작 → latency 를 못 재는 이벤트 타입이 생기면 0 을 넣게 된다.
--                         그리고 INV-4 때문에 그 거짓값을 고칠 수 없다 (영구)
--    감사 로그에서 "측정 안 함"과 "0 이었음"을 섞으면 나중에 되돌릴 방법이 없다.
--
--    반대로 ts / agent / event_type 은 NOT NULL 이다 — 이게 없으면 행 자체가
--    무의미하다. "언제 누가 무엇을"이 빠진 로그 한 줄은 쓸 데가 없다.
-- ─────────────────────────────────────────────────────────────────────
