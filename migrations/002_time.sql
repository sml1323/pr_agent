-- 002_time.sql — agent_events: 시스템에서 일어난 모든 일을 한 줄씩
--
-- 이 표가 답해야 하는 질문들 (이게 컬럼 설계의 기준이다):
--   · "PR 42 리뷰하는 데 얼마 들었나"          → pr_id 로 모아서 cost 합
--   · "어제 왜 비쌌나"                          → ts 로 구간을 잘라서 보기
--   · "이 자동 게시된 코멘트, 무슨 근거였나"    → pr_id 의 줄을 시간순으로
--   · "security 에이전트가 죽었나"              → 그 줄이 없으면 죽은 것
--
-- 마지막 질문이 이 프로젝트에서 가장 무섭다. 에이전트가 조용히 실패하면
-- "critical 없음"과 "확인 못 함"이 구별되지 않고, 게이트는 전자로 착각해 자동 게시한다.
--
-- 재실행 가능 — DROP → CREATE. M2 개발 단계에서는 데이터가 날아가도 된다.
-- ⚠️ 이 DROP 자체가 INV-4 의 다섯 번째 구멍이다. 003 의 트리거로는 DDL 을 막지 못한다.
--    앱 롤에게 DROP 권한을 주지 않는 것으로만 막힌다 → 006_rbac.sql 이 처리한다.

DROP TABLE IF EXISTS agent_events CASCADE;

CREATE TABLE agent_events (
    ts          TIMESTAMPTZ NOT NULL DEFAULT now(),  -- 파티셔닝 컬럼. 항상 "언제"가 먼저다
    agent       TEXT        NOT NULL,                -- 'webhook' | 'queue' | 'security' | 'gate' ...
    event_type  TEXT        NOT NULL,                -- 'received' | 'llm_call' | 'auto_posted' ...
    pr_id       INTEGER,                             -- 시스템 자체 이벤트는 PR 이 없을 수 있다
    -- 아래 세 컬럼은 "해당 없는 이벤트"가 있으므로 셋 다 NULL 을 허용한다. 근거는 파일 끝 주석.
    cost_usd    NUMERIC(10, 6),  -- 달러. 정수부 4자리 + 소수 6자리
    latency_ms  INTEGER,         -- 밀리초. 정수
    tokens      INTEGER,         -- 토큰 수. 정수

    payload     JSONB       NOT NULL DEFAULT '{}'::jsonb
    -- payload 에 무엇을 넣을지(G9)는 여기서 정하지 않는다.
    -- record_event() 를 실제로 쓰는 M3 에서 정한다 — 그게 필요해지는 자리다.
    -- 다만 알고 있어야 할 것: INV-4 로 못 지우므로 한 번 넣은 것은 영구적이다.

    -- PRIMARY KEY 를 두지 않았다. 두려면 파티셔닝 컬럼(ts)을 포함해야 하는데
    -- ("UNIQUE and PRIMARY constraints must include the partitioning key" — TimescaleDB 문서),
    -- append-only 로그는 개별 행을 id 로 집어서 참조할 일이 없다.
    -- 없는 게 정상이고, 필요해지면 그때 넣는다.
)
WITH (
    tsdb.hypertable,

    -- ─────────────────────────────────────────────────────────────────
    -- chunk 간격 — 서랍 하나가 며칠치인가.
    -- ⚠️ WITH (...) 는 저장 파라미터 자리라 상수 리터럴만 받는다.
    --    INTERVAL '1 day' 처럼 타입 캐스트를 쓰면 syntax error 다. 값만 적는다.

    tsdb.chunk_interval = '1 day'

    -- ── 후보 넷 중 하나 ────────────────────────────────────
    --    '1 hour'     '1 day'     '7 days'     '30 days'
    --
    -- ── 계산은 대신 해줬다. 고르는 건 네가 한다 ─────────────
    --
    --    PR 하나당 남는 줄 수:  ①웹훅 + ②큐 + ③워커 + ④에이전트 4개
    --                           + ⑤애그리게이터 + ⑥게이트  ≈ 10줄
    --    개인 토이 레포의 하루 PR:  많아도 5개
    --    → 하루 약 50줄.  한 줄이 payload 포함 대략 1KB → 하루 50KB 정도
    --
    --    후보별로 서랍이 몇 개 생기나 (1년 기준):
    --      '1 hour'   → 8,760개    서랍당 2KB
    --      '1 day'    →   365개    서랍당 50KB
    --      '7 days'   →    52개    서랍당 350KB
    --      '30 days'  →    12개    서랍당 1.5MB
    --
    -- ── 양쪽 실패 모드 ──────────────────────────────────────
    --    너무 잘게  → 서랍이 너무 많다. 플래너가 딱지 읽는 비용만 커진다.
    --                 문서: "maintaining over 1,000 chunks per hypertable is an anti-pattern"
    --    너무 크게  → 서랍이 몇 개 안 된다. 나눈 의미가 줄고, 압축 단위도 통짜에 가까워진다.
    --                 그리고 "지난주만 조회"할 때도 큰 서랍을 열어야 한다.
    --
    -- ── 판단할 것 ──────────────────────────────────────────
    --    위 4개 중 1,000개 안티패턴에 걸리는 건 어느 것인가?
    --    그걸 뺀 나머지 중에서, 우리가 가장 자주 던질 질문("어제/지난주 비용")에
    --    필요한 만큼만 서랍을 열게 하는 건 어느 것인가?
    --
    -- 틀리면 뭐가 깨지나: 지금은 아무것도 안 깨진다 — 데이터가 적어서 체감이 없다.
    -- 그래서 오히려 위험하다. 바꿀 수는 있지만(set_chunk_time_interval)
    -- 이미 만들어진 서랍은 그대로 남는다.
    -- ─────────────────────────────────────────────────────────────────

);

