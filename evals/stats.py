# Pass^k — "k판 **전부** 성공할 확률"
#
# 왜 필요한가: 이 프로젝트의 제1원칙은 선별(틀린 말을 안 하는 것)이다.
# 📖 책 인쇄 217 (7.6.1) — *"일상적인 시나리오에는 Pass@1(단일 시도의 평균 성공률)을
#    중시합니다. **중요한 작업에는 '한 번도 실수하지 않는' 안정성에 초점을 맞춰
#    Pass^k 를 우선합니다.**"*  우리는 후자다.
#
# ⚠️ **`p̂^k` 를 쓰지 않는다.** `x ↦ x^k` 가 볼록이라 젠센 부등식으로 `E[p̂^k] ≥ p^k` —
#    관측 비율을 그냥 거듭제곱하면 **신뢰성을 위로 과대평가한다.**
#
#    🔴 **숫자를 정확히 쓸 것 — 여기서 한 번 틀렸다** (2026-08-28, 적대적 검증에서 발견).
#       원래 이 줄은 *"(c=8, n=12) 에서 k=8 이면 `p̂^k` 가 **참값의 19.3배**"* 였다. **틀렸다.**
#       검산 (p=8/12 를 참값으로 두고):
#
#           참값 p^k                =  0.039018
#           지름길 p̂^k (관측 c=8)   =  0.039018   ← **참값과 같다.** p̂=p 인 점을 골랐으니까
#           불편추정량 C(c,k)/C(n,k)=  0.002020
#           ─────────────────────────────────────
#           지름길 / 불편추정량      = 19.31배     ← M6-PLAN 표의 그 숫자. **두 추정량 사이의 비**
#           E[지름길] / 참값         =  2.41배     ← **이게 기대 편향비다**
#
#       **한 점의 비**와 **기댓값의 비**는 다른 질문의 답이다. 19.3 이 극적이라 인용하기
#       좋은데, 편향의 크기를 말할 땐 **2.41** 이 맞다.
#       ⚠️ 편향은 원리적으로 **한 점에서 안 보인다** — 기댓값에서만 정의된다.
#
#    왜 그런지는 손으로 굴려봐야 붙는다 → `learning/notebooks/02-passk-unbiased.ipynb`.
#    그 노트북 **§2 가 정확히 `E[p̂^k]` 를 계산하게 시킨다** — 그걸 굴려봤으면 위 실수를 안 했다.
#    이 함수는 같은 노트북 §3 과 같은 식이다. **노트북을 먼저 채울 것** —
#    여기 답이 있다고 거기를 건너뛰면, 편향이 어느 방향인지 6개월 뒤에 못 말한다.
#
# ⚠️ **안 닿는 곳**: 여러 픽스처를 합칠 때 집계 p̄ 를 거듭제곱하면 이번엔 **과소**다.
#    → 픽스처별로 먼저 계산하고 평균을 낸다. 그 반대가 아니다 (M6-PLAN §M6-1 ②).
# ─────────────────────────────────────────────────────────────────────
def pass_pow_k_hat(c: int, n: int, k: int) -> float:
    """n판 중 c판 성공을 관측했을 때, "k판 연속 성공"의 **불편추정량**.

        C(c, k) / C(n, k)

    `k > c` 면 `math.comb` 가 0 을 돌려준다 — "성공 판이 k개도 안 되니
    k판 연속을 관측한 적이 없다"는 뜻이다. 0 은 "불가능"이 아니라 **"근거 없음"**이다.
    """
    if not 0 <= c <= n:
        raise ValueError(f"c={c} 가 [0, n={n}] 밖이다")
    if k < 1:
        raise ValueError(f"k={k} 는 1 이상이어야 한다")
    if k > n:
        raise ValueError(f"k={k} 가 판 수 n={n} 보다 크다 — 없는 관측을 묻고 있다")
    return math.comb(c, k) / math.comb(n, k)


