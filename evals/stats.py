# McNemar — 두 설정(프롬프트 A vs B)을 **짝지어** 비교한다
#
# 📖 책 인쇄 222 — *"작업별로 승패를 비교하고 두 설정이 불일치하는 사례(하나는 정답,
#    하나는 오답)만 살펴본 뒤 McNemar 검정 같은 방법으로 유의성을 판단합니다.
#    대응 분석은 작업 난이도에서 오는 공통 잡음을 빼므로 같은 표본 크기에서도
#    독립된 두 성공률의 차이를 보는 것보다 훨씬 민감합니다."*
#
# ⚠️ **우리한테 "짝"이 무엇인가가 함정이다.** 책의 의사코드는
#        for task in paired_tasks: for seed in fixed_seeds: ...
#    인데 **우리 호출엔 seed 를 못 준다**(프록시). 그래서 A 의 판3 과 B 의 판3 은
#    "같은 조건의 두 설정"이 아니라 **그냥 다른 두 난수**다. 판 단위로 짝지으면
#    대응 분석이 빼주기로 한 공통 잡음이 애초에 공유되지 않는다 — **가짜 짝짓기**다.
#
#    → 우리한테 짝의 단위는 **픽스처**다. 그런데 픽스처가 **3개**뿐이라
#      불일치 쌍이 최대 3 이고, 아래 표가 말하듯 그걸론 아무것도 못 가린다:
#
#          n_d = 3 → 최소 양측 p = 0.250
#                5 →              0.062
#                6 →              0.031   ← 여기부터 α=0.05 를 넘길 수 있다
#
#    **그래서 M6-3b 의 첫 걸음은 K를 올리는 게 아니라 픽스처를 늘리는 것이다.**
#    📖 인쇄 222 가 같은 말을 한다 — *"기대 효과가 2~3%포인트에 불과하고 평가 세트가
#       수십 건이라면 개선 효과가 있는지 **평가 자체로 알 수 없습니다.** 이때 우선순위는
#       에이전트를 계속 개선하는 것이 아니라 **평가 세트를 늘리는 것**입니다."*
#    K를 3에서 30으로 올려도 픽스처가 3이면 짝은 여전히 3이다. **축이 다르다.**
# ─────────────────────────────────────────────────────────────────────
def mcnemar_exact(b: int, c: int) -> float:
    """불일치 쌍만 받아 **정확 이항검정**의 양측 p 를 돌려준다.

    Args:
        b: A 는 맞고 B 는 틀린 짝의 수
        c: A 는 틀리고 B 는 맞은 짝의 수
        (둘 다 맞거나 둘 다 틀린 짝은 **안 쓴다** — 그게 대응 분석의 요점이다)

    카이제곱 근사가 아니라 정확검정인 이유: `b+c` 가 한 자릿수다.
    근사는 기대빈도 5 이상을 가정하는데 우리는 그 아래에서 논다.
    """
    # ⚠️ 음수를 막는다 (2026-08-28, 적대적 검증에서 지적). `b=-1, c=1` 이면 `n_d=0` 을
    #    비껴가고 `math.comb` 가 0 을 돌려줘 **p=0.0(최대 유의)** 이 조용히 나온다.
    #    "짝의 개수"가 음수라는 건 세는 쪽 버그이지 통계적 사실이 아니다 — 터뜨린다.
    if b < 0 or c < 0:
        raise ValueError(f"불일치 쌍의 개수가 음수다: b={b}, c={c}")
    n_d = b + c
    if n_d == 0:
        return 1.0  # 불일치가 없다 = 두 설정이 모든 짝에서 같게 굴었다
    # H0: 불일치 쌍이 어느 쪽으로 갈 확률이 반반. 관측만큼 치우칠 확률(양측).
    tail = sum(math.comb(n_d, i) for i in range(min(b, c) + 1)) / 2**n_d
    return min(1.0, 2 * tail)


def min_two_sided_p(n_d: int) -> float:
    """불일치 쌍이 `n_d` 개일 때 **나올 수 있는 가장 작은 양측 p.**

    검정을 돌리기 **전에** 부르는 함수다 — 이 값이 0.05 보다 크면
    어떤 결과가 나와도 유의가 안 나온다. 돌려봐야 답이 정해져 있다.
    """
    if n_d <= 0:
        return 1.0
    return mcnemar_exact(n_d, 0)
